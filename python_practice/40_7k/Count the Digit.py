def nb_dig(n, d):
    
    count = 0


    square_list = [number ** 2 for number in range(0, n +1)]
    str_list =  ', '.join(map(str,square_list))
    for number in str_list:
        if number == str(d):
            count += 1
    return count 
        

def nb_dig(n, d):
    count = 0
    target = str(d) # Переводим d в строку один раз заранее
    
    for k in range(n + 1):
        # 1. Возводим в квадрат
        square = k * k
        # 2. Считаем, сколько раз цифра встречается в этом конкретном квадрате
        count += str(square).count(target)
        
    return count








