def bubble_sort_classic(data_list):
    """Сортирует список методом пузырька в порядке возрастания."""
    
    n = len(data_list)
    
    # 1. Внешний цикл: Определяет, сколько проходов (итераций) нужно сделать.
    # Нам нужно n-1 проходов, так как на последнем уже все будет отсортировано.
    for i in range(n - 1):
        
        # 2. Внутренний цикл: Выполняет сравнение соседних элементов.
        # -i обеспечивает, что мы не проверяем уже отсортированные элементы в конце списка.
        for j in range(n - 1 - i):
            
            # 3. Сравнение и обмен (самая важная часть!)
            # Если элемент слева (j) больше, чем элемент справа (j+1),
            if data_list[j] > data_list[j + 1]:
                
                # Меняем их местами (стандартный "питоновский" обмен)
                data_list[j], data_list[j + 1] = data_list[j + 1], data_list[j]
                
    return data_list

# --- Тест ---
unsorted_list = [64, 34, 25, 12, 22, 11, 90]
print(f"До сортировки: {unsorted_list}")

sorted_list = bubble_sort_classic(unsorted_list)
print(f"После сортировки: {sorted_list}")