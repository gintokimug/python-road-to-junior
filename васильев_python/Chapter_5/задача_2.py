height = 7

for i in range(height):
    if i == 0:
        # Верхушка: 1 звезда в центре поля из 7 символов
        print(f"{'*':^7}")
    elif i == height // 2:
        # Перекладина: 5 звезд в центре поля из 7 символов
        print(f"{'*****':^7}")
    else:
        # Ноги: 2 звезды с пробелами между ними в центре поля из 7 символов
        # Формат '* *' — это крайние точки
        print(f"{'* *':^7}")
